import json, os, re, time, urllib.parse, urllib.request, urllib.error

SRC = os.path.expanduser('~/catholic-companion/frontend/src/data/popes.js')
IMGDIR = os.path.expanduser('~/catholic-companion/frontend/public/popes')
OUT = os.path.expanduser('~/catholic-companion/frontend/src/data/popeImages.js')
UA = {'User-Agent': 'commune-popes/1.0 (personal devotional app)'}
os.makedirs(IMGDIR, exist_ok=True)

src = open(SRC).read()
popes = [(int(n), p) for n, p in re.findall(r"\{ num: (\d+),[^\n]*\n(?:[^\n]*\n){3}\s*born:[^\n]*page: '([^']*)' \}", src)]
if not popes:
    popes = []
    for m in re.finditer(r"\{ num: (\d+),", src):
        tail = src[m.end():m.end() + 600]
        pg = re.search(r"page: '([^']*)'", tail)
        if pg and pg.group(1):
            popes.append((int(m.group(1)), pg.group(1)))
print('popes with an article:', len(popes))

def api(host, params):
    url = f'https://{host}/w/api.php?' + urllib.parse.urlencode(params)
    delay = 2
    for attempt in range(6):
        try:
            return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60))
        except urllib.error.HTTPError as e:
            if e.code not in (429, 503) or attempt == 5:
                raise
            print(f'  {e.code}, waiting {delay}s')
            time.sleep(delay)
            delay *= 2

# lead image per article, 50 at a time
page_file = {}
for i in range(0, len(popes), 50):
    batch = popes[i:i + 50]
    d = api('en.wikipedia.org', {'action': 'query', 'format': 'json', 'formatversion': 2,
                                 'prop': 'pageimages', 'piprop': 'name',
                                 'titles': '|'.join(t for _, t in batch)})
    for pg in d.get('query', {}).get('pages', []):
        if pg.get('pageimage'):
            page_file[pg['title']] = pg['pageimage']
    time.sleep(0.4)
print('articles with a lead image:', len(page_file))

# licence for each file
files = sorted(set(page_file.values()))
CACHE = os.path.expanduser('~/catholic-companion/tools/_pope_licences.json')
lic = {}
if os.path.exists(CACHE):
    lic = {k: tuple(v) for k, v in json.load(open(CACHE)).items()}
    print('cached licences:', len(lic))
files = [f for f in files if f not in lic]
print('still to look up:', len(files))
for n, f in enumerate(files, 1):
    d = api('en.wikipedia.org', {'action': 'query', 'format': 'json', 'formatversion': 2,
                                 'prop': 'imageinfo', 'iiprop': 'extmetadata',
                                 'titles': 'File:' + f})
    pg = (d.get('query', {}).get('pages') or [{}])[0]
    ii = (pg.get('imageinfo') or [{}])[0]
    short = (ii.get('extmetadata', {}).get('LicenseShortName', {}) or {}).get('value', '')
    thumb = ('https://commons.wikimedia.org/wiki/Special:FilePath/'
             + urllib.parse.quote(f.replace(' ', '_')) + '?width=320')
    if short:
        lic[f] = (short, thumb)
    if n % 25 == 0:
        print(' ', n, 'of', len(files), '| known so far:', len(lic))
        json.dump({k: list(v) for k, v in lic.items()}, open(CACHE, 'w'))
    time.sleep(0.35)

json.dump({k: list(v) for k, v in lic.items()}, open(CACHE, 'w'))
print('licences known:', len(lic))

PD = re.compile(r'public domain|^pd', re.I)
kept, skipped, total = {}, [], 0
for num, title in popes:
    f = page_file.get(title)
    if not f: continue
    short, thumb = lic.get(f, ('', None))
    if not thumb or not PD.search(short or ''):
        skipped.append((title, short or 'unknown'))
        continue
    ext = os.path.splitext(thumb)[1].split('?')[0].lower() or '.jpg'
    if ext not in ('.jpg', '.jpeg', '.png'): ext = '.jpg'
    dest = os.path.join(IMGDIR, f'{num}{ext}')
    if not os.path.exists(dest):
        try:
            data = urllib.request.urlopen(urllib.request.Request(thumb, headers=UA), timeout=60).read()
        except Exception as e:
            skipped.append((title, 'download failed')); continue
        open(dest, 'wb').write(data)
        time.sleep(0.15)
    total += os.path.getsize(dest)
    kept[num] = f'/popes/{num}{ext}'

print('public domain portraits kept:', len(kept))
print('skipped for licence or missing:', len(skipped))
for x in skipped[:8]: print('   ', x)
print('total size: %.1f MB' % (total / 1e6))

open(OUT, 'w').write(
"// Portraits for the pope cards. Only files Commons marks public domain are\n"
"// included, so nothing here needs an attribution line. Generated by\n"
"// tools/gen_pope_images.py; rerun it to refresh.\n"
"export const POPE_IMAGES = {\n"
+ ''.join("  %d: '%s',\n" % (k, v) for k, v in sorted(kept.items()))
+ "}\n\nexport default POPE_IMAGES\n")
print('wrote', OUT)
